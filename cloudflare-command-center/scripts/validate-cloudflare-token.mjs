import {appendFileSync} from 'node:fs';

// Read credentials only from Actions secrets. Never log, rewrite, or persist them.
const token=process.env.CLOUDFLARE_API_TOKEN||'';
function fail(message){
 console.error('::error title=Cloudflare deployment secret::'+message);
 if(process.env.GITHUB_STEP_SUMMARY){
  appendFileSync(process.env.GITHUB_STEP_SUMMARY,
   'Cloudflare deployment is blocked: '+message+'\n\n'+
   'Update the **CLOUDFLARE_API_TOKEN environment secret** named `CLOUDFLARE_API_TOKEN` at '+
   '[GitHub deployment environments](https://github.com/superiormandr-star/Fieldnotes/settings/environments). '+
   'Keep the Name unchanged; the Secret field must contain only the raw token generated by Cloudflare. '+
   'This workflow selects the CLOUDFLARE_API_TOKEN Actions environment; its secret overrides the repository secret of the same name. Never put the token in chat, source files, or logs.\n');
 }
 process.exit(1);
}
if(!token)fail('The selected environment has no available Cloudflare API token.');
if(['CLOUDFLARE_API_TOKEN','CLOUDFLARE_API_UNDERSCORE_TOKEN'].includes(token)){
 fail('The saved secret contains a setting name instead of an API token. Replace the Secret field with the actual token generated by Cloudflare.');
}
if(/\s/.test(token)||!/^[A-Za-z0-9._~+/-]+=*$/.test(token)){
 fail('The saved value has invalid token formatting. Save only the raw API token, without whitespace, quotes, an assignment, a command, or an Authorization header.');
}
console.log('Cloudflare token format check passed. Remote permissions are checked by migration and deployment.');
